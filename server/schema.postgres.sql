BEGIN;
-- 브라우저용 Supabase Data API와 분리된 서버 전용 스키마입니다.
CREATE SCHEMA IF NOT EXISTS app_private;
REVOKE ALL ON SCHEMA app_private FROM PUBLIC;

CREATE TABLE IF NOT EXISTS app_private.users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email TEXT NOT NULL UNIQUE,
  name TEXT NOT NULL,
  password_hash TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS app_private.sessions (
  token_hash TEXT PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES app_private.users(id) ON DELETE CASCADE,
  expires_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS sessions_expiry ON app_private.sessions(expires_at);
CREATE TABLE IF NOT EXISTS app_private.auth_attempts (
  bucket TEXT PRIMARY KEY,
  count INTEGER NOT NULL,
  expires_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS auth_attempts_expiry ON app_private.auth_attempts(expires_at);
CREATE TABLE IF NOT EXISTS app_private.academic_state (
  user_id BIGINT PRIMARY KEY REFERENCES app_private.users(id) ON DELETE CASCADE,
  courses JSONB NOT NULL DEFAULT '[]'::jsonb
    CHECK (jsonb_typeof(courses) = 'array' AND jsonb_array_length(courses) <= 500),
  current_year INTEGER NOT NULL DEFAULT 1 CHECK (current_year BETWEEN 1 AND 4),
  revision BIGINT NOT NULL DEFAULT 0 CHECK (revision BETWEEN 0 AND 9007199254740991)
);
-- 웹 사용자는 Node 세션으로 인증합니다. Supabase Auth 사용자용 공개 정책은 만들지 않습니다.
ALTER TABLE app_private.users ENABLE ROW LEVEL SECURITY;
ALTER TABLE app_private.sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE app_private.auth_attempts ENABLE ROW LEVEL SECURITY;
ALTER TABLE app_private.academic_state ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON ALL TABLES IN SCHEMA app_private FROM PUBLIC;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA app_private FROM PUBLIC;
-- 일반 PostgreSQL에서도 실행 가능하도록 Supabase 역할이 있을 때만 권한을 회수합니다.
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
    REVOKE ALL ON SCHEMA app_private FROM anon;
    REVOKE ALL ON ALL TABLES IN SCHEMA app_private FROM anon;
    REVOKE ALL ON ALL SEQUENCES IN SCHEMA app_private FROM anon;
  END IF;
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
    REVOKE ALL ON SCHEMA app_private FROM authenticated;
    REVOKE ALL ON ALL TABLES IN SCHEMA app_private FROM authenticated;
    REVOKE ALL ON ALL SEQUENCES IN SCHEMA app_private FROM authenticated;
  END IF;
END $$;
COMMIT;
